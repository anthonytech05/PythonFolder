# LOOP
"""
Types of loop
for loop and while loop
for loop repeats a block of code for each item in a sequence (list, string, range etc)
while loop keeps running as long as condition is true. use it when you don't know in advance how many iterations you need.
"""

for i in range(20):
    print(f'welcome to python class {i+1}')

statement = 'Python is a great language'
for char in statement:
    print(char)


while True :
    print("HELLOOOOOOOO")
    break
    
 

